const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.resolve('.local/native-internal-annotations-20261115/A002');
const hash=b=>crypto.createHash('sha256').update(b).digest('hex');
const binding=JSON.parse(fs.readFileSync(path.join(root,'ROOT-BINDING.json')));
if(hash(fs.readFileSync(path.join(root,'ROOT-BINDING.json')))!=='4044faf299336f4ea4a9af0246817eaf3176924c5411f26f1cb54ce9ba664be7')throw Error('binding mismatch');
const required=['root','recorderPath','evidenceKind','callCap','elapsedCapS','baselineCalls'].sort();
