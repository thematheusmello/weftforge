#!/usr/bin/env python3
"""Synthetic models/mutants/copies only. No actual UI/native case is assessed."""
import copy
import json
import math
import sys
import tempfile
from pathlib import Path

sys.dont_write_bytecode = True
import grade_saved as G
import retain_saved as R


def run():
    docs, _ = G.models()
    G.grade_states('CUT-R1', docs)
    # One-ulp anchor variation is within the declared measurement tolerance.
    for label in ('cut-r2', 'redo-r4'):
        for identity in (11, 13, 16, 17):
            G.item(docs[label], 'points', identity)['position'][0] = math.nextafter(.09, 1.)
    G.grade_states('CUT-R1', docs)
    r5 = copy.deepcopy(docs['redo-r4'])
    r5['project']['revision'] = 5
    for identity in (5, 17):
        G.item(r5, 'points', identity)['position'][1] = .4
    G.grade_states('CUT-R2', {'child-height-r5': r5}, docs['redo-r4'])
    rejected = []

    def rejects(name, invoke):
        try:
            invoke()
        except (AssertionError, ValueError, KeyError, TypeError, OverflowError, FileExistsError):
            rejected.append(name)
        else:
            raise AssertionError('synthetic mutant accepted: ' + name)

    def bad(name, label, mutate):
        altered = copy.deepcopy(docs)
        mutate(altered[label])
        rejects(name, lambda: G.grade_states('CUT-R1', altered))

    bad('wrong new point', 'cut-r2', lambda d: G.item(d, 'points', 11)['position'].__setitem__(0, .1))
    bad('wrong child ownership', 'cut-r2', lambda d: G.item(d, 'pieces', 15)['boundary'].__setitem__(0, 7))
    bad('wrong object ID', 'cut-r2', lambda d: G.item(d, 'curves', 19).__setitem__('id', 21))
    bad('wrong global object order', 'cut-r2', lambda d: d['project']['points'].reverse())
    bad('wrong revision', 'cut-r2', lambda d: d['project'].__setitem__('revision', 3))
    bad('undo allocator reused', 'undo-r3', lambda d: d['project'].__setitem__('next_id', 11))
    bad('default material changed', 'parent-r1', lambda d: G.item(d, 'materials', 1).__setitem__('damping', .3))
    bad('default mannequin missing', 'parent-r1', lambda d: d['project']['mannequin']['capsules'].pop())
    bad('missing required v4 ownership', 'cut-r2', lambda d: G.item(d, 'pieces', 15).pop('internal_curves'))
    bad('unexpected persistent field', 'cut-r2', lambda d: G.item(d, 'pieces', 15).__setitem__('parent', 2))
    bad('version relabel', 'cut-r2', lambda d: d.__setitem__('version', 3))
    bad('unchanged f64 bit lost', 'parent-r1', lambda d: G.item(d, 'points', 4)['position'].__setitem__(0, math.nextafter(.24, 1.)))
    bad('signed zero lost', 'parent-r1', lambda d: G.item(d, 'points', 3)['position'].__setitem__(0, -0.))
    bad('f32 color changed', 'parent-r1', lambda d: G.item(d, 'materials', 1)['color'].__setitem__(0, .23))
    bad('copied anchor bits differ within tolerance', 'cut-r2', lambda d: G.item(d, 'points', 16)['position'].__setitem__(0, .09))
    bad('redo bits differ within tolerance', 'redo-r4', lambda d: [G.item(d, 'points', n)['position'].__setitem__(0, .09) for n in (11, 13, 16, 17)])
    altered = copy.deepcopy(r5)
    G.item(altered, 'points', 13)['position'][1] = .4
    rejects('reopen mutated retained child', lambda: G.grade_states('CUT-R2', {'child-height-r5': altered}, docs['redo-r4']))
    altered = copy.deepcopy(r5)
    G.item(altered, 'points', 17)['position'][0] = .09
    rejects('reopen changed x bit', lambda: G.grade_states('CUT-R2', {'child-height-r5': altered}, docs['redo-r4']))
    for name, raw in [('duplicate JSON field', b'{"a":1,"a":2}'), ('nonfinite JSON', b'{"a":NaN}')]:
        rejects(name, lambda raw=raw: G.parsed(raw))
    color_equivalent = copy.deepcopy(docs['parent-r1'])
    G.item(color_equivalent, 'materials', 1)['color'][0] = math.nextafter(.22, 1.)
    G.exact(color_equivalent, docs['parent-r1'])
    # Every generated byte below is synthetic and temporary, never an input substitute.
    with tempfile.TemporaryDirectory(prefix='SYNTHETIC-ONLY-', dir=G.ROOT) as name:
        run_path = Path(name)
        (run_path / 'work').mkdir()
        (run_path / 'trace').mkdir()
        previous_raw = None
        for index, label in enumerate(G.CASES['CUT-R1']['labels']):
            raw = (json.dumps(docs[label], indent=1) + '\n\n').encode()
            primary = run_path / G.CASES['CUT-R1']['primary']
            primary.write_bytes(raw)
            if previous_raw is not None:
                Path(str(primary) + '.recovery').write_bytes(previous_raw)
            ids = [str(index * 3 + n).zfill(4) for n in (1, 2, 3)]
            for record, method in zip(ids, ('click', 'getAXStateAndScreenshot', 'fs.raw_snapshot')):
                (run_path / 'trace' / (record + '-before.json')).write_text(json.dumps({'id': record, 'method': method}))
                if record != ids[-1]:
                    (run_path / 'trace' / (record + '-after.json')).write_text(json.dumps({'id': record, 'status': 'returned'}))
            receipt = R.retain(run_path, 'CUT-R1', label, *ids, 'synthetic_selfcheck')
            (run_path / 'trace' / (ids[-1] + '-after.json')).write_text(json.dumps({'id': ids[-1], 'status': 'returned'}))
            G.require((run_path / 'snapshots' / (label + '.weftforge')).read_bytes() == raw, 'synthetic raw copy differs')
            previous_raw = raw
        copied, _ = G.check_receipts(run_path, 'CUT-R1', True)
        G.grade_states('CUT-R1', copied)
        rejects('synthetic receipt cannot be native evidence', lambda: G.check_receipts(run_path, 'CUT-R1'))
        receipt_path = run_path / 'snapshots/redo-r4.receipt.json'
        receipt_raw = receipt_path.read_bytes()

        def bad_receipt(name, mutate):
            changed = json.loads(receipt_raw)
            mutate(changed)
            receipt_path.chmod(0o600)
            receipt_path.write_text(json.dumps(changed))
            receipt_path.chmod(0o444)
            rejects(name, lambda: G.check_receipts(run_path, 'CUT-R1', True))
            receipt_path.chmod(0o600)
            receipt_path.write_bytes(receipt_raw)
            receipt_path.chmod(0o444)

        bad_receipt('receipt wrong case', lambda x: x.__setitem__('case', 'R'))
        bad_receipt('receipt wrong revision', lambda x: x.__setitem__('revision', 3))
        bad_receipt('receipt wrong predecessor', lambda x: x.__setitem__('previous_saved_label', 'parent-r1'))
        bad_receipt('receipt wrong hash', lambda x: x.__setitem__('snapshot_sha256', '0' * 64))
        bad_receipt('receipt missing sidecar absence', lambda x: x['sidecars'].pop('.autosave'))
        bad_receipt('receipt reused source record', lambda x: x.__setitem__('native_save_record', '0001'))
        snapshot = run_path / 'snapshots/redo-r4.weftforge'
        snapshot.chmod(0o600)
        rejects('writable snapshot', lambda: G.check_receipts(run_path, 'CUT-R1', True))
        snapshot.chmod(0o444)
        recovery = run_path / 'snapshots/redo-r4.recovery'
        recovery.chmod(0o600)
        recovery.write_bytes(b'wrong previous primary\n')
        recovery.chmod(0o444)
        rejects('wrong previous-primary recovery bytes', lambda: G.check_receipts(run_path, 'CUT-R1', True))
        binding_raw = b'{"synthetic":true}\n'
        closed = {'schema': G.CLOSURE_SCHEMA, 'case': 'CUT-R1', 'attempt': 'SYNTHETIC-ONLY',
                  'native_input_lease_closed': True, 'outcome': 'completed', 'root_binding_sha256': G.sha(binding_raw),
                  'terminal_source_record': '0012', 'planned_quit_source_record': '0012',
                  'immediate_completion_summary_calls': 1, 'completion_summary_return_receipt': 'COMPLETION-SUMMARY-RETURN.json'}
        closure_path = run_path / 'NATIVE-LEASE-CLOSED.json'
        closure_path.write_text(json.dumps(closed))
        G.closure(run_path, 'CUT-R1', binding_raw)
        for field, replacement in [('case', 'A'), ('native_input_lease_closed', False), ('schema', 'wrong')]:
            changed = copy.deepcopy(closed)
            changed[field] = replacement
            closure_path.write_text(json.dumps(changed))
            rejects('closure ' + field, lambda: G.closure(run_path, 'CUT-R1', binding_raw))
        changed = copy.deepcopy(closed)
        changed['native_case_closed'] = changed.pop('native_input_lease_closed')
        closure_path.write_text(json.dumps(changed))
        rejects('closure alternate field refused', lambda: G.closure(run_path, 'CUT-R1', binding_raw))
    return {'status': 'passed_synthetic_assertions_and_raw_copies_only', 'candidate_executed': False,
            'actual_native_or_UI_case_evaluated': False, 'formal_grade_entrypoint_executed': False,
            'synthetic_models_assessment_only': True, 'generated_native_inputs_retained': False,
            'rejected_mutants': len(rejected), 'checks': rejected}


if __name__ == '__main__':
    parser = __import__('argparse').ArgumentParser()
    parser.add_argument('--report', type=Path, required=True)
    args = parser.parse_args()
    G.require(not args.report.exists(), 'fresh synthetic report required')
    result = run()
    with args.report.open('x') as output:
        json.dump(result, output, indent=2)
        output.write('\n')
    print(json.dumps(result))
